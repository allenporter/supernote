"""Logical key and identifier conventions for blob storage and derived artifacts.

Logical Blob Storage Layout:
- `USER_DATA_BUCKET` ("supernote-user-data"):
  - Primary uploaded user blobs (files, notes, summary handwriting):
    `{uuid4}-{equipment_tail}.{ext}` (generated by `generate_inner_name`)
  - Temporary multipart upload chunks:
    `{object_name}.part.{part_number}` (generated by `get_file_chunk_path`)
- `CACHE_BUCKET` ("supernote-cache"):
  - Rendered note page PNGs:
    `{file_id}/pages/{page_id}.png` (generated by `get_page_png_path`)
  - On-demand converted note PDFs:
    `conversions/{user_id}/{file_id}/note_{file_md5}.pdf` (generated by `get_conversion_pdf_path`)
  - On-demand converted PDFs of a page selection:
    `conversions/{user_id}/{file_id}/note_{file_md5}_pages_{selection}.pdf`

How a `BlobStorage` implementation maps `(bucket, key)` onto physical storage
(e.g. directory sharding on local disk vs. object keys in S3/GCS) is an internal
concern of that `BlobStorage` implementation.
"""

import hashlib
import os
import re
import uuid

CHUNK_PATTERN = re.compile(r"^(.+)\.part\.(\d+)$")
SAFE_PAGE_ID_PATTERN = re.compile(r"^[A-Za-z0-9_-]+$")
PDF_SELECTION_PATTERN = re.compile(r"^(conversions/.+)_pages_[0-9a-f]{16}\.pdf$")


def is_valid_page_id(page_id: str) -> bool:
    """Return whether a notebook page_id is a safe single-segment identifier."""
    return bool(SAFE_PAGE_ID_PATTERN.match(page_id))


def get_page_png_path(file_id: int, page_id: str) -> str:
    """Get the blob storage path for a page PNG."""
    if not is_valid_page_id(page_id):
        raise ValueError(f"Invalid page_id: {page_id!r}")
    return f"{file_id}/pages/{page_id}.png"


def get_file_chunk_path(object_name: str, part_number: int) -> str:
    """Generate a storage path for a file chunk."""
    return f"{object_name}.part.{part_number}"


def parse_file_chunk_name(filename: str) -> str | None:
    """Extract base object name from a multipart chunk filename."""
    match = CHUNK_PATTERN.match(filename)
    return match.group(1) if match else None


def get_summary_id(file_basis: str) -> str:
    """Generate a unique identifier for an AI summary."""
    return f"{file_basis}-summary"


def get_summary_group_id(file_basis: str) -> str:
    """Generate a unique identifier for a summary group."""
    return f"{file_basis}-group"


def get_transcript_id(file_basis: str) -> str:
    """Generate a unique identifier for an OCR transcript."""
    return f"{file_basis}-transcript"


def get_conversion_pdf_prefix(user_id: int, file_id: int, file_md5: str) -> str:
    """Return the key prefix shared by every PDF converted from one note version."""
    return f"conversions/{user_id}/{file_id}/note_{file_md5}"


def get_conversion_pdf_path(
    user_id: int, file_id: int, file_md5: str, page_no_list: list[int] | None = None
) -> str:
    """Generate a storage path for a converted PDF note.

    A page selection gets its own path so that it cannot replace the full
    export, or another selection, while a URL signed for it is still in use.
    """
    prefix = get_conversion_pdf_prefix(user_id, file_id, file_md5)
    if not page_no_list:
        return f"{prefix}.pdf"
    selection = ",".join(str(page_no) for page_no in page_no_list)
    digest = hashlib.sha256(selection.encode()).hexdigest()[:16]
    return f"{prefix}_pages_{digest}.pdf"


def get_full_conversion_pdf_path(key: str) -> str | None:
    """Return the full-export path a page-selection PDF path belongs to."""
    if match := PDF_SELECTION_PATTERN.match(key):
        return f"{match.group(1)}.pdf"
    return None


def generate_inner_name(filename: str, equipment_no: str | None) -> str:
    """Generate a system-of-record inner name.

    Format: {UUID}-{Tail}.{Ext}
    - UUID: Random UUID
    - Tail: Last 3 chars of equipment number (or full if short, default '000')
    """
    req_uuid = uuid.uuid4()
    ext = os.path.splitext(filename)[1]

    # Determine tail
    tail = "000"
    if equipment_no:
        tail = equipment_no[-3:] if len(equipment_no) >= 3 else equipment_no

    return f"{req_uuid}-{tail}{ext}"
